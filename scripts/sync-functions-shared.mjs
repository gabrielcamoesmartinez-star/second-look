// Copies the shared modules the Edge Functions need into supabase/functions/_shared,
// because the Supabase deploy bundler only uploads the functions directory.
// `--check` fails (for CI) if the copies are out of date.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = ['url.ts', 'ssrf.ts', 'errors.ts', 'schemas.ts', 'config.ts'];
const check = process.argv.includes('--check');
const header = '// GENERATED by scripts/sync-functions-shared.mjs from packages/shared/src. Do not edit.\n';
let stale = [];
for (const f of files) {
  const src = header + readFileSync(join(root, 'packages/shared/src', f), 'utf8');
  const dest = join(root, 'supabase/functions/_shared', f);
  if (check) {
    if (!existsSync(dest) || readFileSync(dest, 'utf8') !== src) stale.push(f);
  } else writeFileSync(dest, src);
}
if (check && stale.length) {
  console.error(`supabase/functions/_shared is stale: ${stale.join(', ')}. Run: node scripts/sync-functions-shared.mjs`);
  process.exit(1);
}
